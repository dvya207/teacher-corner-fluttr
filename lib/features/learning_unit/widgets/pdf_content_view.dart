/// A PDF, rendered in the tab: the activity guide, the material list, a die
/// template.
///
/// DOWNLOADED IN FULL BEFORE THE FIRST PAGE, unlike the video beside it, and
/// not by choice: the native viewer renders a local file and has no notion of
/// streaming. The download is cached on the Storage PATH, so the second open
/// of a guide is instant and works with no signal, which is the case that
/// matters. A teacher opens the guide for the activity they are about to run
/// while they still have staff-room wifi.
///
/// A FIXED HEIGHT, NOT THE WHOLE TAB. The pane it sits in scrolls, and a
/// vertically-scrolling PDF inside a vertically-scrolling column is two
/// gestures fighting over one drag. The viewer takes a defined box and pages
/// inside it; the pane scrolls around it.
class PdfContentView extends StatefulWidget {
  const PdfContentView({
    super.key,
    required this.path,
    required this.isUrl,
    this.source,
    this.onOpenExternally,
  });

  /// A Storage path, or a URL when [isUrl].
  final String path;

  final bool isUrl;

  /// Injected by tests, which have no Firebase and no native viewer.
  final StorageFileSource? source;

  /// The way out when the native viewer cannot render a file. Offered rather
  /// than assumed: some PDFs in this data are generated by tools the Android
  /// renderer chokes on, and the browser handles several of those.
  final Future<void> Function()? onOpenExternally;

  @override
  State<PdfContentView> createState() => _PdfContentViewState();
}

class _PdfContentViewState extends State<PdfContentView> {
  File? _file;
  bool _loading = true;
  String? _failure;
  int _pages = 0;
  int _page = 0;

  StorageFileSource get _source =>
      widget.source ?? FirebaseStorageFileSource.instance;

  @override
  void initState() {
    super.initState();
    _fetch();
  }

  @override
  void didUpdateWidget(PdfContentView old) {
    super.didUpdateWidget(old);
    if (old.path != widget.path) _fetch();
  }

  Future<void> _fetch() async {
    setState(() {
      _loading = true;
      _failure = null;
      _file = null;
      _pages = 0;
      _page = 0;
    });
    try {
      // A URL still goes through the cache manager, which is what gives a
      // remote PDF the same offline second-open as a Storage one.
      final file = widget.isUrl
          ? await DefaultCacheManager().getSingleFile(widget.path)
          : await _source.download(widget.path);
      if (!mounted) return;
      setState(() {
        _file = file;
        _loading = false;
      });
    } catch (e) {
      debugPrint('PdfContentView: could not fetch ${widget.path}: $e');
      if (mounted) {
        setState(() {
          _failure = 'lu.pdf_download_failed';
          _loading = false;
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    if (_loading) {
      return _Frame(
        child: const Center(child: CircularProgressIndicator(strokeWidth: 2)),
      );
    }

    final file = _file;
    if (file == null) {
      return _Failure(
        message: _failure ?? 'lu.pdf_download_failed',
        onRetry: _fetch,
        onOpenExternally: widget.onOpenExternally,
      );
    }

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      mainAxisSize: MainAxisSize.min,
      children: [
        _Frame(
          child: PDFView(
            filePath: file.path,
            // VERTICAL, and swiping enabled. A guide is read top to bottom;
            // horizontal paging is for a deck and this is not one.
            swipeHorizontal: false,
            enableSwipe: true,
            autoSpacing: true,
            pageFling: true,
            fitEachPage: true,
            onRender: (pages) {
              if (mounted) setState(() => _pages = pages ?? 0);
            },
            onPageChanged: (page, _) {
              if (mounted) setState(() => _page = page ?? 0);
            },
            onError: (e) {
              debugPrint('PdfContentView: render failed for ${widget.path}: $e');
              if (mounted) setState(() => _failure = 'lu.pdf_render_failed');
            },
          ),
        ),
        if (_failure != null) ...[
          SizedBox(height: AppDimensions.spacing12),
          _Failure(
            message: _failure!,
            onRetry: _fetch,
            onOpenExternally: widget.onOpenExternally,
          ),
        ] else if (_pages > 0) ...[
          SizedBox(height: AppDimensions.spacing8),
          Text(
            'lu.pdf_page_of'.tr(args: ['${_page + 1}', '$_pages']),
            textAlign: TextAlign.center,
            style: AppTypography.tiny,
          ),
        ],
      ],
    );
  }
}

/// The box the viewer draws in. Tall enough that a page of A4 is readable
/// without pinching, which is the only size that makes an in-app guide worth
/// having over the browser.
class _Frame extends StatelessWidget {
  const _Frame({required this.child});

  final Widget child;

  @override
  Widget build(BuildContext context) {
    return Container(
      height: 480.h,
      decoration: BoxDecoration(
        color: AppColors.white,
        borderRadius: BorderRadius.circular(AppDimensions.radiusCard),
        border: Border.all(color: AppColors.borderLight),
      ),
      clipBehavior: Clip.antiAlias,
      child: child,
    );
  }
}

/// Said in words, with the two things that might help.
class _Failure extends StatelessWidget {
  const _Failure({
    required this.message,
    required this.onRetry,
    required this.onOpenExternally,
  });

  final String message;
  final Future<void> Function() onRetry;
  final Future<void> Function()? onOpenExternally;

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: EdgeInsets.all(AppDimensions.spacing16),
      decoration: BoxDecoration(
        color: AppColors.white,
        borderRadius: BorderRadius.circular(AppDimensions.radiusCard),
        border: Border.all(color: AppColors.borderLight),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        mainAxisSize: MainAxisSize.min,
        children: [
          Row(
            children: [
              Icon(
                Icons.picture_as_pdf_outlined,
                size: 24.r,
                color: AppColors.textTertiary,
              ),
              SizedBox(width: AppDimensions.spacing12),
              Expanded(
                child: Text(message.tr(), style: AppTypography.bodyMedium),
              ),
            ],
          ),
          SizedBox(height: AppDimensions.spacing16),
          TcButton(label: 'common.retry'.tr(), onPressed: onRetry),
          if (onOpenExternally != null) ...[
            SizedBox(height: AppDimensions.spacing8),
            TextButton.icon(
              onPressed: () => onOpenExternally!(),
              icon: Icon(Icons.open_in_new_rounded, size: 18.r),
              label: Text('lu.open_externally'.tr()),
            ),
          ],
        ],
      ),
    );
  }
}
